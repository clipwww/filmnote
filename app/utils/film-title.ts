/**
 * 片名的顯示層處理。資料層一律保留原樣，只有畫面上動手腳。
 */

/**
 * 顯示用片名：拿掉書名號。`《》` 在中文字型裡是 1.000 em 全形、跟漢字同寬，片名頭尾各吃掉
 * 一個字寬，在緊湊的票根卡標題特別明顯（`DESIGN_SYSTEM §2.5` 第 3 條：UI 上不顯示《》，
 * 層級改用字重與顏色表達）。
 */
/*
 * ⚠️ 不能只剝頭尾一對：實測片庫 2,669 筆裡有 6 筆同時以《開頭、以》結尾，其中
 * 「《屁屁偵探：咖哩香料事件》 《屁屁偵探：瓢蟲遺跡之謎》」是雙片連映，剝頭尾會得到一個
 * 中間還帶著》《的怪東西 ⇒ 是「移除所有書名號」不是「解開最外層」。
 * `「」『』` 不動——`劇場版「鬼滅之刃」無限城篇` 的引號是片名的一部分。
 */
export function displayTitle(title: string | null | undefined): string {
  if (!title)
    return ''
  return title.replace(/[《》〈〉]/g, '').replace(/\s{2,}/g, ' ').trim()
}
